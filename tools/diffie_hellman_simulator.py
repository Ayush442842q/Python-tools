def main():
    parser = argparse.ArgumentParser(description="Diffie-Hellman Key Exchange Simulator & Educational Visualizer")
    parser.add_argument("-p", type=int, help="Custom prime modulus (p). Must be prime.")
    parser.add_argument("-g", type=int, help="Custom base/generator (g). Must be primitive root modulo p.")
    parser.add_argument("-a", type=int, help="Custom private key for Alice (a).")
    parser.add_argument("-b", type=int, help="Custom private key for Bob (b).")
    parser.add_argument("--speed", type=float, default=1.0, help="Simulation speed multiplier (lower is faster, default 1.0)")
    parser.add_argument("--benchmark", action="store_true", help="Run brute-force scaling benchmark and exit")
    
    args = parser.parse_args()
    
    print_banner()
    
    if args.benchmark:
        run_benchmark()
        return
        
    # Set up or generate parameters
    p = args.p
    g = args.g
    
    if p is None:
        # Generate a friendly prime size for educational visualization (1000-5000)
        p = get_prime_in_range(1000, 5000)
        print(f"[*] Generated random prime modulus p = {p}")
    else:
        if not is_prime(p):
            print(colored(f"[!] Warning: {p} is not prime! The mathematics of DH require a prime modulus.", RED))
            sys.exit(1)
            
    if g is None:
        generators = get_generators(p)
        g = random.choice(generators)
        print(f"[*] Found primitive generator g = {g} for modulus {p}")
        
    a = args.a or random.randint(10, p - 2)
    b = args.b or random.randint(10, p - 2)
    
    # Adjust speed multiplier (inverse: 0.1 speed means sleep is 0.1 * duration)
    run_simulation(p, g, a, b, args.speed)

if __name__ == "__main__":
    main()
