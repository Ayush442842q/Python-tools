API_URL = "https://www.toptal.com/developers/gitignore/api"

def get_online_targets():
    """Fetch the list of all supported targets from gitignore.io."""
    try:
        req = urllib.request.Request(
            f"{API_URL}/list?format=json",
            headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"}
        )
        with urllib.request.urlopen(req, timeout=5) as response:
            data = response.read().decode('utf-8')
            # The API returns a JSON list or a comma-separated text
            if data.startswith('{') or data.startswith('['):
                return json.loads(data)
            else:
                # Comma separated / newline separated targets
                targets = []
                for line in data.split('\n'):
                    targets.extend([t.strip().lower() for t in line.split(',') if t.strip()])
                return sorted(list(set(targets)))
    except Exception as e:
        print(f"Warning: Failed to fetch online targets list: {e}. Using offline targets.", file=sys.stderr)
        return sorted(list(OFFLINE_TEMPLATES.keys()))

def generate_gitignore(targets, offline=False):
    """Generate gitignore content for the specified targets."""
    content = []
    
    if offline:
        print("Using offline mode...", file=sys.stderr)
        for target in targets:
            target_lower = target.lower()
            if target_lower in OFFLINE_TEMPLATES:
                content.append(f"### {target} (Offline Template) ###\n" + OFFLINE_TEMPLATES[target_lower])
            else:
                print(f"Warning: Offline template for '{target}' not found. Skipping.", file=sys.stderr)
        return "\n".join(content)
        
    try:
        targets_str = ",".join(targets)
        url = f"{API_URL}/{targets_str}"
        req = urllib.request.Request(
            url,
            headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"}
        )
        print(f"Fetching .gitignore for: {targets_str}...", file=sys.stderr)
        with urllib.request.urlopen(req, timeout=8) as response:
            return response.read().decode('utf-8')
    except urllib.error.URLError as e:
        print(f"Network error: {e}. Falling back to offline templates.", file=sys.stderr)
        # Attempt fallback
        return generate_gitignore(targets, offline=True)
    except Exception as e:
        print(f"Unexpected error fetching from API: {e}. Falling back to offline templates.", file=sys.stderr)
        return generate_gitignore(targets, offline=True)

def main():
    parser = argparse.ArgumentParser(
        description="Generate standard .gitignore files from gitignore.io or offline templates."
    )
    parser.add_argument('targets', nargs='*', help='Templates to generate (e.g. python vscode)')
    parser.add_argument('-l', '--list', action='store_true', help='List common / supported templates')
    parser.add_argument('-o', '--output', default='.gitignore', help='Output file path (default: .gitignore)')
    parser.add_argument('-a', '--append', action='store_true', help='Append to output file instead of overwriting')
    parser.add_argument('--offline', action='store_true', help='Force offline mode using built-in templates')
    
    args = parser.parse_args()
    
    if args.list:
        if args.offline:
            print("Common Offline Templates:")
            for t in sorted(OFFLINE_TEMPLATES.keys()):
                print(f"  - {t}")
        else:
            print("Fetching supported templates list...")
            targets = get_online_targets()
            print("\nSupported gitignore templates (total: {}):".format(len(targets)))
            
            # Print in columns
            cols = 4
            for i in range(0, len(targets), cols):
                chunk = targets[i:i+cols]
                print("".join(f"{t:<20}" for t in chunk))
        return 0
        
    if not args.targets:
        parser.print_help()
        return 1
        
    content = generate_gitignore(args.targets, offline=args.offline)
    
    if not content.strip():
        print("Error: No valid content was generated.", file=sys.stderr)
        return 1
        
    mode = 'a' if args.append else 'w'
    action_str = "Appending to" if args.append else "Writing to"
    
    try:
        with open(args.output, mode, encoding='utf-8') as f:
            if args.append and os.path.exists(args.output) and os.path.getsize(args.output) > 0:
                f.write("\n\n")
            f.write(content)
        print(f"Success: {action_str} {args.output} for targets: {', '.join(args.targets)}")
        return 0
    except Exception as e:
        print(f"Error writing to output file: {e}", file=sys.stderr)
        return 1

if __name__ == "__main__":
    sys.exit(main())
