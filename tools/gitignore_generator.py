#!/usr/bin/env python3
"""
gitignore_generator - Generate standard .gitignore files

A utility to generate high-quality .gitignore files for various programming languages,
frameworks, operating systems, and IDEs using the Toptal gitignore.io API,
with built-in offline fallbacks for common environments.

Usage:
    python tools/gitignore_generator.py [targets...] [options]

Options:
    -h, --help            Show this help message and exit
    -l, --list            List available/common gitignore templates
    -o OUTPUT, --output OUTPUT
                          Output file path (default: .gitignore)
    -a, --append          Append to the existing output file instead of overwriting
    --offline             Force offline mode using built-in templates
    targets               List of templates to combine (e.g. python vscode node)

Examples:
    python tools/gitignore_generator.py python vscode
    python tools/gitignore_generator.py rust windows --output .gitignore
    python tools/gitignore_generator.py node --append
"""

